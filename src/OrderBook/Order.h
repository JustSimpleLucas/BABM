// Order.h

#ifndef ABM_ORDER_BOOK_ORDER_H
#define ABM_ORDER_BOOK_ORDER_H

#include <cstddef>
#include <cstdint>

namespace abm {

/**
 * Direction of an order submitted to the market microstructure.
 *
 * The explicit side is kept separate from signed quantities so that CSV exports
 * and execution accounting can distinguish buyer and seller records without
 * relying on sign conventions.
 */
enum class OrderType : std::uint8_t { BUY, SELL };

/**
 * Execution style requested for an order.
 *
 * Limit orders can rest in the persistent book when they do not immediately
 * cross. Market orders consume available opposite-side liquidity and discard
 * any unfilled residual quantity.
 */
enum class OrderStyle : std::uint8_t { LIMIT, MARKET };

/**
 * Order generated by an agent strategy and completed by the market coordinator.
 *
 * Orders are intentionally small data records. The simulation clearing layer
 * validates cash, inventory, and short-selling constraints before execution so
 * strategy classes can focus on behavioural signal formation. Lifecycle fields
 * are assigned centrally so price-time priority is reproducible for a fixed
 * seed.
 */
struct Order {
    int orderId{0};
    int ownerAgentId{0};

    /** Index into SimulationConfig::assets identifying the traded asset. */
    std::uint32_t assetIndex{0};

    OrderType type{OrderType::BUY};
    OrderStyle style{OrderStyle::LIMIT};
    double price{0.0};
    double quantity{0.0};
    double remainingQuantity{0.0};
    int timeStep{0};
    std::size_t creationTimeStep{0};
    std::size_t expiryTimeStep{0};
    std::size_t sequence{0};
};

} // namespace abm

#endif // ABM_ORDER_BOOK_ORDER_H
